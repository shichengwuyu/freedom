/** 从「分镜图片提示词」字符串中解析 角色三视图/场景四宫格/道具标准图 三个子模板 */
export const parseAssetTemplates = (source: string): Record<string, string> => {
    const result: Record<string, string> = {};
    const sections = source.split("【").filter(Boolean);
    for (const section of sections) {
        const nameEnd = section.indexOf("】");
        if (nameEnd === -1) continue;
        const name = section.slice(0, nameEnd);
        const body = section.slice(nameEnd + 1).trim();
        if (body) result[name] = body;
    }
    return result;
};
